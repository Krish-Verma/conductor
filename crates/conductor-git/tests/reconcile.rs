#[test]
fn a_remote_added_inside_the_clone_is_policy_sensitive_even_with_an_identical_tree() {
    // Acceptance row 14. The tree never changes, so a classifier that keyed only
    // on the tree would return NO_CHANGE and the mutation would vanish. This is
    // the reason `NO_CHANGE` is checked *after* the structural deltas.
    let run = run();
    git(
        run.path(),
        &["remote", "add", "evil", "https://example.invalid/x.git"],
    );

    let result = classify(&run, &["**"]);

    assert_eq!(result.verdict, Verdict::PolicySensitive, "{result:?}");
    assert!(
        result
            .findings()
            .iter()
            .any(|f| f.kind == FindingKind::RemoteChanged),
        "{:?}",
        result.findings()
    );
    assert!(
        result
            .findings()
            .iter()
            .any(|f| f.kind == FindingKind::ConfigChanged),
        "a remote is config; both diffs must see it: {:?}",
        result.findings()
    );
}

