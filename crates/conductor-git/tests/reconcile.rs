//! `reconcile()` — master plan §4.8.
//!
//! Every verdict here is produced from a **hand-constructed git state**: a real
//! clone, mutated the way the thing being modelled would mutate it, then
//! observed and classified. Asserting the classifier against structs it was
//! written alongside would prove only that the author was self-consistent.

mod common;

use std::path::Path;

use conductor_core::{PolicyHash, RunId, TaskId};
use conductor_git::baseline::observe;
use conductor_git::clone::{WorkspaceRequest, create_workspace};
use conductor_git::reconcile::{
    AgentReport, FindingKind, ReportClaim, Scope, SensitivePatterns, Verdict, VerificationOutcome,
    reconcile,
};

use common::{clean_repo, git, git_out, write};

struct Run {
    _source: common::Fixture,
    _root: tempfile::TempDir,
    ws: conductor_git::Workspace,
}

impl Run {
    fn path(&self) -> &Path {
        &self.ws.path
    }
}

/// A workspace cloned from a clean source at its HEAD.
fn run() -> Run {
    let source = clean_repo();
    let root = tempfile::tempdir().expect("tempdir");
    let path = root.path().join("run");
    let head = git_out(source.path(), &["rev-parse", "HEAD"]);
    let ws = create_workspace(&WorkspaceRequest {
        source: source.path().to_path_buf(),
        workspace: path,
        run_id: RunId::new("r-0041").expect("valid"),
        task_id: TaskId::new("T-0012").expect("valid"),
        base_commit: head,
        policy_hash: PolicyHash::new("blake3:deadbeef").expect("valid"),
    })
    .expect("create");
    Run {
        _source: source,
        _root: root,
        ws,
    }
}

/// Observe and classify with everything in scope and no report.
fn classify(run: &Run, scope: &[&str]) -> conductor_git::reconcile::Reconciliation {
    let observed = observe(run.path(), &run.ws.baseline).expect("observe");
    reconcile(
        &run.ws.baseline,
        &observed,
        &Scope::new(scope.iter().map(|s| (*s).to_string())),
        &SensitivePatterns::default(),
        None,
        None,
    )
}

#[test]
fn nothing_happened_is_no_change() {
    let run = run();
    let result = classify(&run, &["**"]);
    assert_eq!(result.verdict, Verdict::NoChange, "{result:?}");
    assert!(result.findings().is_empty(), "{:?}", result.findings());
}

