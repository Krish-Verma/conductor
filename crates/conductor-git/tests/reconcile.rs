#[test]
fn the_run_branch_advancing_is_not_a_ref_finding() {
    // Committing on the run branch is the whole point of the run. A ref diff
    // that flagged it would make every successful run look like an attack.
    let run = run();
    write(run.path(), "src/lib.rs", "pub fn one() -> u32 { 11 }\n");
    git(run.path(), &["add", "-A"]);
    git(run.path(), &["commit", "-q", "-m", "agent work"]);

    let result = classify(&run, &["src/**"]);
    assert!(
        !result
            .findings()
            .iter()
            .any(|f| matches!(f.kind, FindingKind::RefChanged | FindingKind::RefRemoved)),
        "{:?}",
        result.findings()
    );
}

